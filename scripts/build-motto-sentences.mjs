// Generate lib/motto-sentences.ts (with inline data array) from
// data/motto-sentences.enriched.json.
//
// Why: the Shadowing page is a client component and needs the corpus
// synchronously at render time. Static-importing a JSON is fragile (build
// ordering, fs in client bundles) — inlining the data into a TS file
// gives a single, deterministic import path.
//
// Run after scripts/gpt-mini-batch-furigana.mjs completes.

import { readFile, writeFile } from "node:fs/promises";

const INPUT = "F:/WebSite/Japanese-learning-compare/data/motto-sentences.enriched.json";
const OUTPUT = "F:/WebSite/Japanese-learning-compare/lib/motto-sentences.ts";

const TEMPLATE = (rows) => `// AUTO-GENERATED by scripts/build-motto-sentences.mjs — do not edit by hand.
// Regenerate after running scripts/gpt-mini-batch-furigana.mjs.

import type { MottoSentence } from "./motto-sentences-types";

export const MOTTO_SENTENCES: MottoSentence[] = ${rows};

export const TOTAL_MOTTO_SENTENCES = MOTTO_SENTENCES.length;
`;

async function main() {
  let raw;
  try {
    raw = await readFile(INPUT, "utf-8");
  } catch (e) {
    console.error(`❌ ${INPUT} not found. Run scripts/gpt-mini-batch-furigana.mjs first.`);
    process.exit(1);
  }
  const data = JSON.parse(raw);
  // Drop transient fields (error from gpt-mini-batch failures) and rename
  // the STT script's `url` to `audioUrl` to match lib/motto-sentences-types.ts.
  // TypeScript's structural typing rejects object literals with extra keys
  // (`Object literal may only specify known properties`) — so we strip
  // everything that's not part of MottoSentence here.
  const mapped = data.map((entry) => {
    const { error: _e, url, ...rest } = entry;
    return { ...rest, audioUrl: url };
  });
  const rows = JSON.stringify(mapped, null, 2)
    .replace(/,(\s*[}\]])/g, "$1");
  const out = TEMPLATE(rows);
  await writeFile(OUTPUT, out, "utf-8");
  console.log(`✅ ${data.length} entries → ${OUTPUT}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(99);
});